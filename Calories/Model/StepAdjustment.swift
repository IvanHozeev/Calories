import Foundation

/// Насколько этот день был подвижнее или ленивее обычного — в килокалориях.
///
/// Измеренный расход считается по неделям: он говорит, сколько человек тратит
/// в среднем, и молчит о том, что среда со сменой на ногах и воскресенье на
/// диване — это не один и тот же день. У живого человека разброс огромный:
/// от полутора тысяч шагов до двадцати шести за месяц, то есть почти
/// двадцатикратный. Размазывать такую неделю ровным слоем — значит в один день
/// требовать дефицита, которого нет, а в другой прощать перебор.
///
/// Шаги — метрика косвенная: они не знают ни про штангу, ни про велосипед. Но
/// это единственное, что телефон считает каждый день без просьб, и как признак
/// «сегодня наработался больше обычного» они работают.
///
/// Поправка считается от **личного** среднего, а не от абсолютного числа шагов:
/// среднее уже сидит внутри измеренного расхода, и прибавлять его второй раз
/// нельзя. Прибавляется только отклонение — и за неделю такие поправки в сумме
/// дают почти ноль, поэтому оценка расхода от них не едет.
enum StepAdjustment {
    /// Сколько дней с шагами нужно, чтобы поправка включилась.
    ///
    /// Это и есть период привыкания: пока приложение не видело две недели
    /// активности, оно не знает, что для этого человека «обычный день», и
    /// молчит вместо того, чтобы гадать.
    static let minimumDays = 14
    /// По какому окну считается «обычный день».
    static let baselineWindow = 28
    /// Нетто-стоимость шага на килограмм веса.
    ///
    /// Ходьба стоит примерно половину килокалории на килограмм на километр
    /// сверх покоя; в километре около 1330 шагов. Для семидесяти шести
    /// килограммов это ≈0.029 ккал на шаг, то есть привычные «десять тысяч
    /// шагов — около трёхсот килокалорий».
    static let kcalPerStepPerKg = 0.000375
    /// Насколько поправка вправе сдвинуть день.
    ///
    /// Потолок нужен не ради шагов, а ради ошибок в них: браслет, забытый на
    /// зарядке, или телефон, проехавший день в машине, не должны переписывать
    /// норму в полтора раза.
    static let maxShareOfExpenditure = 0.15

    /// «Обычный день» этого человека — среднее число шагов за окно.
    ///
    /// Сегодняшний день не в счёт: он ещё идёт и среднее бы занижал.
    /// nil — данных пока мало, поправка не включается.
    static func baseline(from history: [StepDay],
                         now: Date = Date(),
                         window: Int = baselineWindow,
                         calendar: Calendar = .current) -> Int? {
        let today = calendar.startOfDay(for: now)
        guard let from = calendar.date(byAdding: .day, value: -window, to: today) else { return nil }
        let days = history.filter { $0.date >= from && $0.date < today && $0.steps > 0 }
        guard days.count >= minimumDays else { return nil }
        return Int((Double(days.reduce(0) { $0 + $1.steps }) / Double(days.count)).rounded())
    }

    /// Поправка к расходу за день, в килокалориях.
    ///
    /// - Parameter partialDay: день ещё идёт. Тогда поправка не уходит в минус:
    ///   утром шагов нет ни у кого, и срезать за это норму — значит требовать
    ///   от человека голодать за то, что он ещё не успел походить. Вверх она
    ///   при этом работает: находил лишние десять тысяч — ешь.
    static func adjustment(steps: Int?,
                           baseline: Int?,
                           weightKg: Double?,
                           expenditure: Double,
                           partialDay: Bool = false) -> Double {
        guard let steps, let baseline, let weightKg, baseline > 0, expenditure > 0 else { return 0 }
        let raw = Double(steps - baseline) * weightKg * kcalPerStepPerKg
        let limit = expenditure * maxShareOfExpenditure
        let capped = min(max(raw, -limit), limit)
        return partialDay ? max(0, capped) : capped
    }
}
