import Foundation

/// Во что превращается сухое при варке.
///
/// Сто грамм сухих макарон — это двести пятьдесят отварных, и в дневник идут
/// именно отварные: взвешивают то, что на тарелке. Сейчас этот пересчёт
/// человек делает руками — варит, взвешивает, спрашивает у чужой нейросети,
/// сколько вышло на сто грамм, — и так каждый раз.
///
/// Вся арифметика держится на одном факте: **при варке калории не меняются**.
/// Крупа набирает воду, вода калорий не несёт. Значит хранить нужно одно
/// число — во сколько раз тяжелеет продукт, — а калории и макросы остаются
/// теми же, просто размазываются по большему весу.
///
/// Отсюда и точность: ошибиться можно только в весе, но не в энергии. Даже
/// грубый коэффициент даёт верные калории блюда — он влияет лишь на то,
/// сколько граммов готового приложение насчитает.
enum CookingYield {

    /// Справочные коэффициенты: во сколько раз тяжелеет сто грамм сухого.
    ///
    /// Начальные значения, а не истина: у каждой плиты, кастрюли и привычки
    /// «аль денте» коэффициент свой. Как только человек взвесит готовое,
    /// приложение возьмёт его собственный — см. `learn(dry:cooked:)`.
    /// Числа подвинуты по живому замеру: пятьсот грамм макарон Barilla дают
    /// около 1160 готовых, это ×2.3, а не ×2.6. Справочники пишут про
    /// «аль денте» и про разваренные одинаково, и ошибаются вверх.
    ///
    /// В «Крупы и хлеб» попадает и хлеб, который не варят вовсе, — но вес
    /// ему никто и не пересчитывает: коэффициент предлагается, а применяется
    /// только к тому, что человек положил в блюдо сухим.
    static let reference: [FoodCategory: Double] = [
        .grains: 2.3,
        .legumes: 2.3,
    ]

    /// Ниже и выше этого коэффициент считается опиской.
    ///
    /// Втрое с небольшим набирает рис, вдвое с небольшим — макароны; всё, что
    /// за этими границами, — почти наверняка перепутанные местами сухой и
    /// готовый вес. Молча принять такое значит испортить вес блюда вдвое.
    static let allowed: ClosedRange<Double> = 1.1...4.0

    /// Разумно ли это число как коэффициент.
    static func isPlausible(_ factor: Double) -> Bool { allowed.contains(factor) }

    /// Коэффициент по измерению: сварили из сухого — получили готовое.
    ///
    /// nil, когда числа не складываются в коэффициент: нулевой вес, готовое
    /// легче сухого (так бывает у жарки, но это уже не уваривание), или
    /// значения перепутаны местами.
    static func learn(dry: Double, cooked: Double) -> Double? {
        guard dry > 0, cooked > 0 else { return nil }
        let factor = cooked / dry
        return isPlausible(factor) ? factor : nil
    }

    /// Сколько получится готового из сухого веса.
    static func cookedGrams(dry: Double, factor: Double) -> Double {
        dry * factor
    }

    /// Сколько сухого ушло на готовый вес — обратный пересчёт.
    ///
    /// Нужен там, где человек взвесил тарелку, а состав продукта задан на
    /// сухое: тогда калории считаются по сухому эквиваленту.
    static func dryGrams(cooked: Double, factor: Double) -> Double {
        guard factor > 0 else { return cooked }
        return cooked / factor
    }

    /// Калорийность ста грамм готового продукта.
    ///
    /// Делим, а не пересчитываем: энергия та же, вес больше. Сто грамм
    /// отварных макарон несут столько же калорий, сколько сорок грамм сухих.
    static func cookedPer100g(dryPer100g: Double, factor: Double) -> Double {
        guard factor > 0 else { return dryPer100g }
        return dryPer100g / factor
    }

    /// Макросы ста грамм готового — по тому же правилу.
    static func cookedMacros(dryPer100g: Macros, factor: Double) -> Macros {
        guard factor > 0 else { return dryPer100g }
        return Macros(protein: dryPer100g.protein / factor,
                      fat: dryPer100g.fat / factor,
                      carbs: dryPer100g.carbs / factor)
    }
}
