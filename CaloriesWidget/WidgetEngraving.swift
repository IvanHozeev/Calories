import SwiftUI
import WidgetKit

/// Та же вдавленность, что на экранах приложения: кольца и полосы прогресса —
/// канавки, прорезанные в поверхности виджета. Гравируется только пустая часть;
/// сам цвет остаётся плоским и светящимся, как был, — рельеф на нём гасит цвет.
///
/// Копия, а не общий файл, по той же причине, что и намерения контролов: папки
/// проекта синхронизированы с файловой системой, и членство в таргете задаётся
/// папкой. Копия здесь не дословная и не станет ею: у виджета нет светлой темы —
/// он всегда на своём тёмном градиенте, — зато есть режим отрисовки, которого
/// нет в приложении. Если правишь глубину в `Engraving`, загляни и сюда.
///
/// Физика та же: свет падает сверху, верхняя стенка бросает тень вниз, нижняя
/// ловит свет. Числа привязаны к толщине канавки — кольца в виджетах тоньше
/// экранных (5–6 пунктов против 9), и фиксированное размытие съело бы их целиком.
enum WidgetEngraving {
    /// Пустая канавка. Дно светлее фона: фон виджета тёмный, затемнять его ещё
    /// раз некуда, а канавку надо видеть целиком — по ней читается остаток.
    static func channel(thickness: CGFloat, mode: WidgetRenderingMode) -> AnyShapeStyle {
        walls(over: Color.white.opacity(0.08), thickness: thickness, mode: mode)
    }

    private static func walls(over style: some ShapeStyle,
                              thickness: CGFloat,
                              mode: WidgetRenderingMode) -> AnyShapeStyle {
        // На тонированном домашнем экране и на блокировке система перекрашивает
        // виджет в один цвет по яркости пикселей. Рельеф там не читается как
        // рельеф — он превращается в грязь по краям и съедает контраст между
        // пустой канавкой и заполненной. Отдаём плоскую заливку.
        guard mode == .fullColor else { return AnyShapeStyle(style) }
        let wall = thickness / 3
        return AnyShapeStyle(
            style
                .shadow(.inner(color: .black.opacity(0.9), radius: wall, x: 0, y: wall))
                .shadow(.inner(color: .white.opacity(0.26), radius: wall * 0.7, x: 0, y: -wall * 0.7))
        )
    }
}
