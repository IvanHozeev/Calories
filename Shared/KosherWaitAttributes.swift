import ActivityKit
import Foundation

/// Ожидание между мясным и молочным — на экране блокировки и в островке.
///
/// Смысл именно в том, что приложение закрыто: человек поел и ушёл, а вопрос
/// «можно ли уже» не должен требовать открывать дневник. Отсчёт идёт по часам
/// системы — запись делается один раз, вместе с временем конца, и больше её
/// никто не трогает.
///
/// Лежит в `Shared`, потому что нужна обоим: приложение её заводит, виджет
/// рисует. Поэтому здесь нет ни `KosherStatus`, ни чего-либо ещё из модели —
/// только то, что переживёт границу таргета.
struct KosherWaitAttributes: ActivityAttributes {
    struct ContentState: Codable, Hashable {
        /// Когда ожидание кончится. Островок сам считает до него.
        var until: Date
    }

    /// Чего ждём: `meat` или `dairy`. Строкой, а не перечислением из модели, —
    /// у виджета своего доступа к ней нет, а менять формат ради одного слова
    /// значит ломать уже идущие записи.
    var blocked: String
    /// Когда съели то, из-за чего ждём: строка под отсчётом называет причину.
    var since: Date

    static let meat = "meat"
    static let dairy = "dairy"

    /// Диапазон для системного отсчёта: конец не раньше начала.
    ///
    /// `Text(timerInterval:)` принимает обычный диапазон дат, а Swift требует
    /// от него, чтобы нижняя граница была не больше верхней, — иначе проверка
    /// валит процесс. Срок же ожидания рано или поздно наступает: приложение
    /// в этот момент может не работать и активность не закрыть, а система
    /// продолжает перерисовывать её по своим часам. Каждая перерисовка после
    /// срока роняла расширение — так набралось сто девяносто восемь падений
    /// за шесть дней, по одному на каждую попытку показать островок.
    ///
    /// После срока диапазон пустой, и отсчёт стоит на нуле — ровно то, что он
    /// и значит: ждать больше нечего.
    static func countdownRange(now: Date, until: Date) -> ClosedRange<Date> {
        now...max(until, now)
    }
}
