import SwiftUI

/// Цвет числа калорий по тому, насколько дёшевы сто граммов.
///
/// Шкала односторонняя и только вниз: чем дешевле сто граммов, тем зеленее
/// число; обычная и плотная еда остаётся обычным цветом. Это сделано
/// намеренно.
///
/// Светофор на еде был бы приговором. Красные 654 ккал у грецкого ореха
/// читались бы как «ты сделал что-то не то» — хотя орехом как раз и
/// закрывают норму по жирам, а оливковое масло ничем не провинилось. К тому
/// же красный и оранжевый в этом приложении уже заняты: ими говорят про
/// натрий и перебор калорий, и третий смысл сделал бы их все неразличимыми.
///
/// Зелёный же здесь ничего не обещает и ни к чему не призывает: он просто
/// говорит, что этого можно съесть много и остаться в норме. Тот же зелёный
/// носят значки «почти без калорий» и «можно много» — у цвета остаётся одно
/// значение на всё приложение, а шкала добавляет к ним ступени: видно
/// разницу между сорока пятью и девяноста, а не только «лист есть / нет».
enum EnergyDensity {
    /// Выше этого сто граммов считаются обычными, и зелёного нет совсем.
    ///
    /// Полтораста — там, где кончается еда, которую едят тарелками: варёная
    /// крупа, творог, фрукты, мясо. Выше идёт то, что меряют ложками, и
    /// подсвечивать там нечего.
    static let plainFrom = 150.0

    /// Насколько «дёшевы» сто граммов: 1 — почти без калорий, 0 — обычная еда.
    static func cheapness(caloriesPer100g kcal: Int) -> Double {
        guard kcal > 0 else { return 1 }
        return max(0, min(1, (plainFrom - Double(kcal)) / plainFrom))
    }

    /// Цвет числа. Без калорийности ста граммов — обычный: не знаем, значит
    /// не красим.
    ///
    /// Меняется насыщенность, а не доля чёрного. Первая попытка подмешивала
    /// зелёный к цвету текста — то есть к чёрному, — и выходил грязный
    /// тёмный оттенок, неотличимый от обычной цифры: подсветка была, а
    /// увидеть её было нельзя. Здесь зелёный остаётся зелёным на всей шкале,
    /// а дешевизна ста граммов читается по его силе.
    static func tint(_ caloriesPer100g: Int?) -> Color {
        guard let kcal = caloriesPer100g else { return .primary }
        let cheap = cheapness(caloriesPer100g: kcal)
        guard cheap > 0 else { return .primary }
        // Тон — тот же, что у «Овощей и фруктов» на диаграмме состава:
        // зелёный в этом приложении один на всё.
        return Color(hue: 0.38,
                     saturation: 0.45 + 0.35 * cheap,
                     brightness: 0.72 + 0.10 * cheap)
    }

    /// Вес числа по той же шкале: чем дешевле сто граммов, тем жирнее.
    ///
    /// Цвет и вес говорят одно и то же, и это не повтор, а страховка. Зелёный
    /// на зелёном фоне плитки, при дальтонизме, при беглом взгляде боковым
    /// зрением — теряется; вес виден всегда и не зависит от того, как человек
    /// различает оттенки. Два признака одного свойства сходятся, а не спорят.
    ///
    /// Ступенями, а не плавно: у шрифта весов конечное число, и плавная
    /// шкала всё равно легла бы на них же — только непредсказуемо.
    static func weight(_ caloriesPer100g: Int?) -> Font.Weight {
        guard let kcal = caloriesPer100g else { return .semibold }
        switch cheapness(caloriesPer100g: kcal) {
        case ..<0.25:  return .semibold
        case ..<0.55:  return .bold
        case ..<0.80:  return .heavy
        default:       return .black
        }
    }
}
