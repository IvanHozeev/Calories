import Foundation

/// Как кольцу дня появиться при запуске.
///
/// Заставка уходит, увеличившись, и на её месте начинается день. Чтобы это
/// читалось одним движением, а не подменой, кольцо подхватывает знак с его
/// последнего размера и дорастает до своего.
///
/// Состояний три, а не два, из-за случая «заставки не было»: её выключают
/// «Уменьшением движения» и флагом запуска в UI-тестах. Логическим «да/нет»
/// этот случай не отличить от «заставка ещё идёт», и кольцо осталось бы
/// маленьким и невидимым навсегда.
enum RingEntrance {
    /// Появляться нечему: заставки не было, кольцо сразу своего размера.
    case none
    /// Заставка идёт, кольцо ждёт под ней.
    case waiting
    /// Заставка ушла — расти.
    case grow
}
